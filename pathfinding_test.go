func testAllFinders(t *testing.T, name string, factory func() Finder) {
	expected, ok := jsExpected[name]
	if !ok {
		t.Fatalf("unknown finder: %s", name)
	}
	for i, s := range testScenarios {
		grid := NewGrid(s.matrix)
		finder := factory()
		path := finder.FindPath(s.startX, s.startY, s.endX, s.endY, grid)
		if path == nil {
			t.Errorf("[%s] scenario %d: path not found", name, i+1)
			continue
		}
		if !pathEqual(path, expected.paths[i]) {
			t.Errorf("[%s] scenario %d:\n  got:  %v\n  want: %v", name, i+1, path, expected.paths[i])
		}
	}
}

func pathEqual(a, b [][2]int) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// Test all 13 finders against JS reference.
func TestAllAgainstJS(t *testing.T) {
	testAllFinders(t, "AStar", func() Finder { return NewAStarFinder(nil) })
	testAllFinders(t, "BestFirst", func() Finder { return NewBestFirstFinder(nil) })
	testAllFinders(t, "Dijkstra", func() Finder { return NewDijkstraFinder(nil) })
	testAllFinders(t, "BreadthFirst", func() Finder { return NewBreadthFirstFinder(nil) })
	testAllFinders(t, "BiAStar", func() Finder { return NewBiAStarFinder(nil) })
	testAllFinders(t, "BiBestFirst", func() Finder { return NewBiBestFirstFinder(nil) })
	testAllFinders(t, "BiDijkstra", func() Finder { return NewBiDijkstraFinder(nil) })
	testAllFinders(t, "BiBreadthFirst", func() Finder { return NewBiBreadthFirstFinder(nil) })
	testAllFinders(t, "IDAStar", func() Finder { return NewIDAStarFinder(nil) })
	testAllFinders(t, "JPFAtMostOne", func() Finder {
		return JumpPointFinder(&FinderOptions{DiagonalMovement: DiagonalIfAtMostOneObstacle})
	})
	testAllFinders(t, "JPFNever", func() Finder {
		return JumpPointFinder(&FinderOptions{DiagonalMovement: DiagonalNever})
	})
	testAllFinders(t, "JPFAlways", func() Finder {
		return JumpPointFinder(&FinderOptions{DiagonalMovement: DiagonalAlways})
	})
	testAllFinders(t, "JPFOnlyWhenNoObstacles", func() Finder {
		return JumpPointFinder(&FinderOptions{DiagonalMovement: DiagonalOnlyWhenNoObstacles})
	})
}
